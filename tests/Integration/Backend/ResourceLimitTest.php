/**
 * The per-job limits with real programs: every job the memory estimate admits converts within the memory ceiling,
 * which is the address space limit of every backend process, and a process stopped by its address space or CPU time
 * limit is reported as resource_limit.
 *
 * The content jobs (CONTENT_INPUTS, generated by ContentImages) are inputs that need more memory than noise of the same
 * size, at sizes the default Limits allow: screenshots of 1920 x 1080 and 3840 x 2160, still GIFs of 2000 x 2000 and
 * 1000 x 1000 (random colours, half of the pixels transparent), a 256-colour PNG, and enlargements of 1000 x 1000 to
 * 6000 x 6000. Each runs at the default and the highest effort, to AVIF and WEBP (the enlargements to JPEG and WEBP),
 * once through every enabled backend that accepts it and once through the resolver of all enabled backends. Each job
 * must either convert with a verified output or be refused with ResourceLimitException before anything runs, because
 * its estimate is above the ceiling; any other outcome, conversion_failed included, fails the test. The time limits of
 * these jobs and of the noise jobs are raised to two hours: the defaults (30 seconds, 60 seconds of CPU time) stop the
 * slowest of them, which is a time limit, not a memory one.
 *
 * Run count with all six backends of tests/docker: at the default effort and the highest WEBP and JPEG efforts, 81
 * jobs alone and 23 through the resolver; at the highest effort to AVIF, in the extra group "slow" (avifenc takes
 * minutes per megapixel of screen content), 13 jobs alone and 5 through the resolver. A resolver job whose backend
 * and job already ran alone in the same process reuses that outcome instead of converting again.
 *
 * @covers \Mfonte\SecureImageConverter\Backend\AbstractBackend
 * @covers \Mfonte\SecureImageConverter\Backend\BackendResolver
 * @covers \Mfonte\SecureImageConverter\Backend\Internal\ProcessFailure
 *
 * @group backends
 */
#[CoversClass(AbstractBackend::class)]
#[CoversClass(BackendResolver::class)]
#[CoversClass(ProcessFailure::class)]
#[Group('backends')]
final class ResourceLimitTest extends BackendTestCase
{
    /**
     * Mode of the content jobs that runs them through the resolver of all enabled backends.
     */
    private const ALL = 'all';

    /**
     * Inputs of the content jobs: content, encoding (png, indexed or gif; jpeg for a flat JPEG), size, output size.
     */
    private const CONTENT_INPUTS = [
        'screenshot 1920x1080' => [ContentImages::SCREEN, 'png', 1920, 1080, 1920, 1080],
        'screenshot 3840x2160' => [ContentImages::SCREEN, 'png', 3840, 2160, 3840, 2160],
        'still GIF 2000x2000' => [ContentImages::PALETTE_NOISE_ALPHA, 'gif', 2000, 2000, 2000, 2000],
        'still GIF 1000x1000' => [ContentImages::PALETTE_NOISE_ALPHA, 'gif', 1000, 1000, 1000, 1000],
        '256-colour PNG 1920x1080' => [ContentImages::PALETTE_SCREEN_ALPHA, 'indexed', 1920, 1080, 1920, 1080],
        'screenshot 1000x1000 to 6000x6000' => [ContentImages::SCREEN, 'png', 1000, 1000, 6000, 6000],
        'JPEG 1000x1000 to 6000x6000' => ['', 'jpeg', 1000, 1000, 6000, 6000],
    ];

    /**
     * Time limit of the content jobs, in seconds of wall-clock and of CPU time.
     */
    private const CONTENT_SECONDS = 7200;

    /**
     * Outcomes of the content jobs run so far in this process, by backend and job: null when the output was
     * verified, "refused" when the estimate was above the ceiling, else what went wrong.
     *
     * @var array<string, string|null>
     */
    private static $outcomes = [];

    /**
     * Backends with the time limits of the content jobs, by name.
     *
     * @var array<string, AbstractBackend>
     */
    private static $contentBackends = [];

    /**
     * Inputs generated by this test, by name.
     *
     * @var array<string, array{0: string, 1: ImageInfo}>
     */
    private $inputs = [];

    /**
     * Each enabled backend alone, and the resolver of all of them, with each content input.
     *
     * @return array<string, array{0: string, 1: string}>
     */
    public static function contentJobs(): array
    {
        $cases = [];
        foreach (array_merge(self::enabledNames(), [self::ALL]) as $mode) {
            foreach (array_keys(self::CONTENT_INPUTS) as $input) {
                $cases[$mode . ', ' . $input] = [$mode, $input];
            }
        }

        return $cases;
    }

    /**
     * The content jobs without enlargement, for the highest-effort AVIF jobs.
     *
     * @return array<string, array{0: string, 1: string}>
     */
    public static function slowContentJobs(): array
    {
        return array_filter(self::contentJobs(), static function (array $case): bool {
            return self::CONTENT_INPUTS[$case[1]][2] === self::CONTENT_INPUTS[$case[1]][4];
        });
    }

    /**
     * The content jobs at the default effort, and at the highest effort to WEBP and JPEG.
     *
     * @dataProvider contentJobs
     */
    #[DataProvider('contentJobs')]
    public function testAnAdmittedContentJobConvertsWithinTheCeiling(string $mode, string $input): void
    {
        $this->assertContentJobs($mode, $input, false);
    }

    /**
     * The content jobs at the highest effort to AVIF, the slowest: minutes per megapixel of screen content.
     *
     * @dataProvider slowContentJobs
     *
     * @group slow
     */
    #[DataProvider('slowContentJobs')]
    #[Group('slow')]
    public function testAnAdmittedHighestEffortAvifJobConvertsWithinTheCeiling(string $mode, string $input): void
    {
        $this->assertContentJobs($mode, $input, true);
    }

    /**
     * Every output format a backend encodes from noisy RGBA PNGs, the costliest content for every encoder but AV1:
     * at the default effort, 3000 x 2000 pixels with 8 bits per channel, and 1500 x 1500 with 16 bits and lossless;
     * at the highest effort, 1000 x 750 (400 x 300 for AVIF). gif2webp converts an animated GIF of 6 frames of 0.6
     * megapixels at the default and the highest effort. Each job converts, or is refused before it runs because its
     * estimate is above the ceiling. The time limits are those of the content jobs: under the default 30 seconds, a
     * 6 megapixel AVIF encode can time out when the other runs of a parallel test load the host.
     *
     * @dataProvider enabledBackends
     */
    #[DataProvider('enabledBackends')]
    public function testAnAdmittedNoiseJobConvertsWithinTheCeiling(string $name): void
    {
        self::requireLevel(IsolationLevel::RLIMIT);
        self::backend($name);
        $backend = self::contentBackend($name);
        $capabilities = $backend->getCapabilities();
        $jobs = [];
        foreach ($capabilities->getOutputFormats() as $output) {
            if (in_array(ImageFormat::PNG, $capabilities->getInputFormats(), true)) {
                $jobs[] = $this->job($this->png(3000, 2000, true), $output);
                $jobs[] = $this->job($this->png(1500, 1500, true, 16), $output);
                if (in_array($output, $capabilities->getLosslessFormats(), true)) {
                    $jobs[] = $this->job($this->png(1500, 1500, true), $output)->withLossless(true);
                }
                $small = $output === ImageFormat::AVIF ? $this->png(400, 300, true) : $this->png(1000, 750, true);
                $jobs[] = $this->job($small, $output)->withEffort(ConversionRequest::EFFORT_MAX);
            } elseif (in_array(ImageFormat::GIF, $capabilities->getAnimatedInputFormats(), true)) {
                $jobs[] = $this->job($this->gif(1000, 600, 6), $output);
                $jobs[] = $this->job($this->gif(1000, 600, 6), $output)->withEffort(ConversionRequest::EFFORT_MAX);
            }
        }
        $jobs = array_filter($jobs, static function (BackendJob $job) use ($capabilities): bool {
            return $capabilities->explainUnsupported($job) === null;
        });
        if ($jobs === []) {
            self::markTestSkipped(sprintf('The %s backend decodes neither PNG nor animated GIF.', $name));
        }
        $failures = [];
        foreach ($jobs as $job) {
            $problem = self::outcome($backend, $job);
            if ($problem !== null && $problem !== 'refused') {
                $failures[] = sprintf('%s, %d bits, effort %d: %s', self::label($job), $job->getInput()->getBitDepth(), $job->getEffort(), $problem);
            }
        }

        self::assertSame([], $failures);
    }

    /**
     * vips below the address space it needs: whether the loader, the thread pool or an allocation fails, the run is
     * a resource limit.
     */
    public function testAnAddressSpaceKillIsAResourceLimit(): void
    {
        self::requireLevel(IsolationLevel::RLIMIT);
        $backend = self::backend(VipsBackend::NAME);
        $job = $this->job($this->png(4000, 3000, false), ImageFormat::WEBP);
        $directory = $this->workingDirectory();
        self::assertTrue(symlink($job->getInputPath(), $directory->pathOf('input.png')));
        $environment = ['VIPS_CONCURRENCY' => '1', 'VIPS_BLOCK_UNTRUSTED' => '1', 'MALLOC_ARENA_MAX' => '2'];

        foreach ([96, 128, 160] as $mebibytes) {
            $result = $backend->createJobRunner($mebibytes * 1048576, $environment)
                ->execute($backend->commandLine($job), $directory, null, [$job->getInputPath()]);

            self::assertFalse($result->isSuccessful(), sprintf('vips converted 12 megapixels within %d MiB.', $mebibytes));
            self::assertInstanceOf(
                ResourceLimitException::class,
                ProcessFailure::exception($backend->getName(), $result),
                sprintf('%d MiB: exit code %s, signal %s: %s', $mebibytes, var_export($result->getExitCode(), true), var_export($result->getSignal(), true), $result->getStderr())
            );
        }
    }

    /**
     * A slow job under a CPU time limit of one second fails with ResourceLimitException, from the kill and neither
     * from the memory estimate nor from the address space limit: a noisy image at the highest effort, of 6 megapixels to AVIF, or of 20 megapixels to
     * lossless WEBP (GD's encoder ignores the effort: its worker took 2.3 seconds of CPU time for 6 megapixels in
     * tests/docker and 8.1 for 20, and converted 6 megapixels within the limit on GitHub's runners).
     *
     * @dataProvider enabledBackends
     */
    #[DataProvider('enabledBackends')]
    public function testACpuTimeKillIsAResourceLimit(string $name): void
    {
        self::requireLevel(IsolationLevel::RLIMIT);
        self::backend($name);
        $options = new ProcessOptions();
        $options = $options->withResourceLimits($options->getResourceLimits()->withCpuSeconds(1));
        $backend = BackendFactory::create($name, self::hostRunner($options), self::backendOptions());
        self::assertInstanceOf(AbstractBackend::class, $backend);
        $capabilities = $backend->getCapabilities();
        self::requireAvailable($capabilities, $backend);
        if (!in_array(ImageFormat::PNG, $capabilities->getInputFormats(), true)) {
            self::markTestSkipped(sprintf('The %s backend does not decode PNG.', $name));
        }
        $output = in_array(ImageFormat::AVIF, $capabilities->getOutputFormats(), true) ? ImageFormat::AVIF : ImageFormat::WEBP;
        $job = $this->job($output === ImageFormat::AVIF ? $this->png(3000, 2000, true) : $this->png(5000, 4000, true), $output)
            ->withEffort(9)
            ->withQuality(100);
        if ($output === ImageFormat::WEBP && in_array(ImageFormat::WEBP, $capabilities->getLosslessFormats(), true)) {
            $job = $job->withLossless(true);
        }
        if ($capabilities->explainUnsupported($job) !== null) {
            self::markTestSkipped(sprintf('The %s backend encodes neither AVIF nor WEBP from PNG.', $name));
        }
        self::assertLessThanOrEqual(self::backendOptions()->getMemoryCeilingBytes(), $backend->estimateMemoryBytes($job), 'the job is admitted');

        try {
            $backend->convert($job);
            self::fail(sprintf('The %s backend converted the job within one second of CPU time.', $name));
        } catch (ResourceLimitException $exception) {
            // The CPU limit kills with a signal: SIGXCPU, or SIGKILL at the hard limit (prlimit sets both).
            // The address space limit makes an allocation fail instead, which the backend reports as a memory or
            // pixel budget exceeded or as memory exhaustion, never as a kill.
            self::assertMatchesRegularExpression('/ was killed \(signal (?:9|24)\): /', $exception->getMessage());
        }
    }

    private function assertContentJobs(string $mode, string $input, bool $slow): void
    {
        self::requireLevel(IsolationLevel::RLIMIT);
        if ($mode === self::ALL) {
            $backends = [];
            foreach (self::availableBackends() as $backend) {
                $backends[] = self::contentBackend($backend->getName());
            }
            $resolver = new BackendResolver($backends);
        } else {
            self::backend($mode);
            $backends = [self::contentBackend($mode)];
            $resolver = null;
        }
        $failures = [];
        $converted = 0;
        foreach ($this->contentJobsOf($input, $slow) as $job) {
            if ($resolver === null) {
                if ($backends[0]->getCapabilities()->explainUnsupported($job) !== null) {
                    continue;
                }
                $backend = $backends[0];
                $chosen = $job;
            } else {
                if (!self::anyBackendAccepts($backends, $job)) {
                    continue;
                }
                try {
                    $selection = $resolver->resolve($job);
                } catch (ResourceLimitException $exception) {
                    continue;
                } catch (\Exception $exception) {
                    $failures[] = sprintf('%s, effort %d: %s: %s', self::label($job), $job->getEffort(), get_class($exception), $exception->getMessage());
                    continue;
                }
                $backend = $selection->getBackend();
                $chosen = $selection->getJob();
            }
            $problem = self::outcome($backend, $chosen);
            if ($problem === null) {
                ++$converted;
            } elseif ($problem !== 'refused') {
                $failures[] = sprintf('%s, effort %d, %s: %s', self::label($chosen), $chosen->getEffort(), $backend->getName(), $problem);
            }
        }

        self::assertSame([], $failures, sprintf('%d jobs converted.', $converted));
    }

    /**
     * Converts a job once per process (an input is known by its file name) and returns null when the output was
     * verified, "refused" when the estimate is above the ceiling and the backend refused the job with
     * ResourceLimitException, or what went wrong.
     */
    private static function outcome(BackendInterface $backend, BackendJob $job): ?string
    {
        $key = implode('|', [
            $backend->getName(),
            basename($job->getInputPath()),
            $job->getOutputFormat(),
            $job->getWidth(),
            $job->getHeight(),
            $job->getFit(),
            $job->getEffort(),
            $job->needsLosslessMode() ? 'lossless' : 'lossy',
            $job->isAnimated() ? 'animated' : 'still',
        ]);
        if (array_key_exists($key, self::$outcomes)) {
            return self::$outcomes[$key];
        }
        if ($backend->estimateMemoryBytes($job) > self::backendOptions()->getMemoryCeilingBytes()) {
            try {
                $backend->convert($job);
                $outcome = 'converted although its estimate is above the ceiling';
            } catch (ResourceLimitException $exception) {
                $outcome = strpos($exception->getMessage(), 'above the memory ceiling') !== false ? 'refused' : $exception->getMessage();
            } catch (\Exception $exception) {
                $outcome = sprintf('%s: %s', get_class($exception), $exception->getMessage());
            }
        } else {
            $outcome = self::check($backend, $job);
        }

        return self::$outcomes[$key] = $outcome;
    }

    /**
     * The jobs of a content input: AVIF at the highest effort when $slow, else AVIF at the default effort and WEBP at
     * the default and the highest effort (JPEG and WEBP for an enlargement).
     *
     * @return list<BackendJob>
     */
    private function contentJobsOf(string $name, bool $slow): array
    {
        list($content, $encoding, $width, $height, $outputWidth, $outputHeight) = self::CONTENT_INPUTS[$name];
        $input = $this->contentInput($content, $encoding, $width, $height);
        $enlarged = $outputWidth !== $width;
        if ($slow) {
            $plan = [[ImageFormat::AVIF, ConversionRequest::EFFORT_MAX]];
        } else {
            $other = $enlarged ? ImageFormat::JPEG : ImageFormat::AVIF;
            $plan = [
                [$other, ConversionRequest::DEFAULT_EFFORT],
                [ImageFormat::WEBP, ConversionRequest::DEFAULT_EFFORT],
                [ImageFormat::WEBP, ConversionRequest::EFFORT_MAX],
            ];
            if ($enlarged) {
                $plan[] = [ImageFormat::JPEG, ConversionRequest::EFFORT_MAX];
            }
        }
        $jobs = [];
        foreach ($plan as list($format, $effort)) {
            $job = $this->job($input, $format, $outputWidth, $outputHeight)->withEffort($effort);
            $jobs[] = $enlarged ? $job->withFit(ConversionRequest::FIT_FILL) : $job;
        }

        return $jobs;
    }

    /**
     * @param list<AbstractBackend> $backends
     */
    private static function anyBackendAccepts(array $backends, BackendJob $job): bool
    {
        foreach (BackendResolver::fallbackFormats($job->getOutputFormat(), $job->getInputFormat()) as $format) {
            foreach ($backends as $backend) {
                if ($backend->getCapabilities()->explainUnsupported($job->withOutputFormat($format)) === null) {
                    return true;
                }
            }
        }

        return false;
    }

    /**
     * A backend like self::backend(), with the time limits of the content jobs.
     */
    private static function contentBackend(string $name): AbstractBackend
    {
        if (!isset(self::$contentBackends[$name])) {
            $options = new ProcessOptions();
            $options = $options->withTimeoutSeconds((float) self::CONTENT_SECONDS)
                ->withResourceLimits($options->getResourceLimits()->withCpuSeconds(self::CONTENT_SECONDS));
            $backend = BackendFactory::create($name, self::hostRunner($options), self::backendOptions());
            self::assertInstanceOf(AbstractBackend::class, $backend);
            self::requireAvailable($backend->getCapabilities(), $backend);
            self::$contentBackends[$name] = $backend;
        }

        return self::$contentBackends[$name];
    }

    /**
     * A content input in the working directory (ContentImages; a flat JPEG for "jpeg").
     *
     * @param positive-int $width
     * @param positive-int $height
     *
     * @return array{0: string, 1: ImageInfo}
     */
    private function contentInput(string $content, string $encoding, int $width, int $height): array
    {
        $name = sprintf('%s-%s-%dx%d', $content !== '' ? $content : 'flat', $encoding, $width, $height);
        if (isset($this->inputs[$name])) {
            return $this->inputs[$name];
        }
        switch ($encoding) {
            case 'png':
                $data = ContentImages::png($content, $width, $height);
                break;
            case 'indexed':
                $data = ContentImages::indexedPng($content, $width, $height);
                break;
            case 'gif':
                $data = ContentImages::gif($content, $width, $height);
                break;
            default:
                $data = ImageBuilder::jpeg($width, $height, 3);
        }
        $format = $encoding === 'gif' ? ImageFormat::GIF : ($encoding === 'jpeg' ? ImageFormat::JPEG : ImageFormat::PNG);
        $path = $this->workingDirectory()->pathOf($name . '.' . ImageFormat::extension($format));
        file_put_contents($path, $data);
        $info = self::inspect($path);
        self::assertNotNull($info, 'The generated input is not valid: ' . $name);

        return $this->inputs[$name] = [$path, $info];
    }

    /**
     * An animated GIF in the working directory whose frames alternate between two patterns of black and white
     * pixels, so that no encoder can merge them.
     *
     * @param positive-int $width
     * @param positive-int $height
     *
     * @return array{0: string, 1: ImageInfo}
     */
    private function gif(int $width, int $height, int $frames): array
    {
        $name = sprintf('large-%dx%dx%d.gif', $width, $height, $frames);
        if (isset($this->inputs[$name])) {
            return $this->inputs[$name];
        }
        $data = ImageBuilder::gifScreen($width, $height) . "\x21\xFF\x0BNETSCAPE2.0\x03\x01\x00\x00\x00";
        for ($frame = 0; $frame < $frames; ++$frame) {
            // A clear code before every pixel keeps the LZW codes three bits wide.
            $writer = new BitWriter();
            for ($pixel = $width * $height; $pixel > 0; --$pixel) {
                $writer->write(4, 3);
                $writer->write(($pixel + $frame) & 1, 3);
            }
            $writer->write(5, 3);
            $data .= "\x21\xF9\x04\x04\x0A\x00\x00\x00\x2C" . pack('vvvvC', 0, 0, $width, $height, 0) . "\x02"
                . ImageBuilder::gifSubBlocks($writer->getBytes());
        }
        $path = $this->workingDirectory()->pathOf($name);
        file_put_contents($path, $data . "\x3B");

        return $this->inputs[$name] = [$path, new ImageInfo(ImageFormat::GIF, $width, $height, $frames, (int) filesize($path))];
    }

    /**
     * An RGBA PNG in the working directory, with 8 or 16 bits per channel: uniform, or of random pixels, which take
     * encoders the longest and the most memory.
     *
     * @param positive-int $width
     * @param positive-int $height
     * @param 8|16         $bitDepth
     *
     * @return array{0: string, 1: ImageInfo}
     */
    private function png(int $width, int $height, bool $noise, int $bitDepth = 8): array
    {
        $name = sprintf('large-%dx%d-%s-%d.png', $width, $height, $noise ? 'noise' : 'flat', $bitDepth);
        if (isset($this->inputs[$name])) {
            return $this->inputs[$name];
        }
        $bytes = $bitDepth === 16 ? 8 : 4;
        $rows = '';
        $row = "\0" . str_repeat($bitDepth === 16 ? "\x80\x80\x40\x40\x20\x20\xFF\xFF" : "\x80\x40\x20\xFF", $width);
        for ($y = 0; $y < $height; ++$y) {
            $rows .= $noise ? "\0" . random_bytes($width * $bytes) : $row;
        }
        $data = $noise ? ImageBuilder::zlibStored($rows) : (string) gzcompress($rows, 1);
        $path = $this->workingDirectory()->pathOf($name);
        file_put_contents($path, "\x89PNG\r\n\x1a\n" . ImageBuilder::pngHeader($width, $height, $bitDepth, 6) . ImageBuilder::pngChunk('IDAT', $data) . ImageBuilder::pngChunk('IEND', ''));
        $info = (new ImageInfo(ImageFormat::PNG, $width, $height, 1, (int) filesize($path)))->withBitDepth($bitDepth);

        return $this->inputs[$name] = [$path, $info];
    }
}
